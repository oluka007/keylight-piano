"""Writes LICENSES/blocksd-dependencies.md: every Python package frozen into the bundled
blocksd daemon, with its licence and the licence text shipped in that package's metadata.
Run after scripts/build-blocksd.sh, with the build's own interpreter (read-only):
  native/build/darwin-arm64/blocksd-work/venv/bin/python -I scripts/blocksd-licenses.py
"""
import importlib.metadata as md
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
BUNDLED = ['blocksd', 'python-rtmidi', 'typer', 'rich', 'pydantic', 'pydantic-core', 'annotated-types',
           'annotated-doc', 'typing-extensions', 'typing-inspection', 'markdown-it-py', 'mdurl', 'pygments',
           'shellingham']


def licence_of(dist):
    meta = dist.metadata
    expr = meta.get('License-Expression')
    if expr:
        return expr
    cls = [c.split('::')[-1].strip() for c in (meta.get_all('Classifier') or []) if c.startswith('License ::')]
    return ', '.join(cls) or (meta.get('License') or 'see text')[:60]


def texts_of(dist):
    out = []
    for f in dist.files or []:
        name = f.name.upper()
        if ('LICENSE' in name or 'COPYING' in name or 'NOTICE' in name) and f.suffix.lower() in ('', '.txt', '.md', '.rst'):
            if 'sboms' in str(f):
                continue
            out.append((str(f), dist.locate_file(f).read_text(encoding='utf-8', errors='replace').strip()))
    return out


rows, blocks = [], []
for name in BUNDLED:
    d = md.distribution(name)
    rows.append(f"| {d.metadata['Name']} | {d.version} | {licence_of(d)} | {d.metadata.get('Home-page') or ''} |")
    for path, text in texts_of(d):
        blocks.append(f"### {d.metadata['Name']} {d.version} ({path})\n\n```text\n{text}\n```\n")

py = f"{sys.version_info.major}.{sys.version_info.minor}.{sys.version_info.micro}"
cpython = pathlib.Path(sys.base_prefix) / f"lib/python{sys.version_info.major}.{sys.version_info.minor}/LICENSE.txt"
head = f"""# Python packages inside the bundled light daemon

Keylight's Mac app carries [blocksd](https://github.com/hyperb1iss/blocksd) v0.6.0 (ISC, see
`blocksd-ISC.txt`) as a frozen program (`Contents/Resources/blocksd`, built by
`scripts/build-blocksd.sh`). It contains CPython {py} (Python Software Foundation licence, text
below) and the packages in this table. Generated by `scripts/blocksd-licenses.py` from the
build's own package metadata; every licence is permissive and none needs source to be offered.

Also in the folder: PyInstaller's bootloader (GPL-2.0-or-later with the special exception that
allows distributing programs it builds under any licence), python-rtmidi's bundled RtMidi
(MIT-style licence by Gary Scavone, included in the python-rtmidi text below), and the Rust
code of pydantic-core (MIT; its dependency licences are in the package's metadata).

| Package | Version | Licence | Home page |
|---|---|---|---|
""" + "\n".join(rows) + "\n\n## Licence texts\n\n" + "\n".join(blocks)
head += f"\n## CPython {py}\n\n```text\n{cpython.read_text(encoding='utf-8', errors='replace').strip()}\n```\n"
(ROOT / 'LICENSES' / 'blocksd-dependencies.md').write_text(head, encoding='utf-8')
print('wrote LICENSES/blocksd-dependencies.md', len(head), 'bytes,', len(rows), 'packages')
